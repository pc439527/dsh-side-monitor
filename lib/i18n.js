/**
 * Translate a key into the given language, filling {name} placeholders.
 * Falls back to zh-CN, then to the raw key.
 * @param {string} lang - 'zh-CN' | 'en-US'
 * @param {string} key - message key
 * @param {Record<string,string|number>} [vars] - placeholder values
 */
export function t(lang, key, vars) {
  let text =
    (messages[lang] && messages[lang][key]) ||
    (messages['zh-CN'] && messages['zh-CN'][key]) ||
    key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split('{' + k + '}').join(String(v))
    }
  }
  return text
}

/** Resolve the persisted language, defaulting to zh-CN (never the browser). */
export function resolveLanguage(storage) {
  try {
    const v = storage ? storage.getItem(LANGUAGE_KEY) : null
    if (v && LANGUAGES.includes(v)) return v
  } catch { /* storage unavailable */ }
  return 'zh-CN'
}

/** Validate that both tables carry exactly the same keys (used by tests). */
export function validateTables() {
  const a = Object.keys(messages['zh-CN']).sort()
  const b = Object.keys(messages['en-US']).sort()
  const onlyA = a.filter((k) => !b.includes(k))
  const onlyB = b.filter((k) => !a.includes(k))
  return { ok: onlyA.length === 0 && onlyB.length === 0, onlyA, onlyB }
}
